-- PostgreSQL bootstrap for the read-only article migration.
-- Run once in Render's SQL console; the Render connector currently allows read-only queries.
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(120) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS articles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_id BIGINT NOT NULL REFERENCES users(id),
 status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','review','changes','published','archived')),
 featured_image VARCHAR(255),
 published_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS article_translations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
 locale VARCHAR(20) NOT NULL,
 title VARCHAR(255) NOT NULL,
 slug VARCHAR(220) NOT NULL,
 excerpt TEXT,
 content TEXT NOT NULL DEFAULT '',
 status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','published')),
 UNIQUE(locale,slug),
 UNIQUE(article_id,locale)
);
CREATE INDEX IF NOT EXISTS articles_status_published_idx ON articles(status,published_at DESC);
CREATE INDEX IF NOT EXISTS translations_status_locale_idx ON article_translations(status,locale);
-- This is a minimal compatibility schema, not the complete original CMS schema.
