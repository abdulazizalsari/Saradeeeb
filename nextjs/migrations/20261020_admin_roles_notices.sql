-- Additive port of PHP admin authorization, notes, preferences, restrictions,
-- site notices and community category translations. No admin grants seeded.
CREATE TABLE IF NOT EXISTS admin_roles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug VARCHAR(80) NOT NULL UNIQUE, name VARCHAR(160) NOT NULL,
 description VARCHAR(500), is_system BOOLEAN NOT NULL DEFAULT TRUE,
 created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS admin_permissions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slug VARCHAR(120) NOT NULL UNIQUE, name VARCHAR(160) NOT NULL,
 group_name VARCHAR(80) NOT NULL, created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_admin_permissions_group ON admin_permissions(group_name);
CREATE TABLE IF NOT EXISTS admin_role_permissions (
 role_id BIGINT NOT NULL REFERENCES admin_roles(id) ON DELETE CASCADE,
 permission_id BIGINT NOT NULL REFERENCES admin_permissions(id) ON DELETE CASCADE,
 PRIMARY KEY(role_id,permission_id)
);
CREATE TABLE IF NOT EXISTS admin_user_roles (
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 role_id BIGINT NOT NULL REFERENCES admin_roles(id) ON DELETE CASCADE,
 assigned_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ DEFAULT now(), PRIMARY KEY(user_id,role_id)
);
CREATE TABLE IF NOT EXISTS admin_user_permissions (
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 permission_id BIGINT NOT NULL REFERENCES admin_permissions(id) ON DELETE CASCADE,
 effect VARCHAR(10) NOT NULL CHECK(effect IN ('allow','deny')),
 assigned_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now(),
 PRIMARY KEY(user_id,permission_id)
);
CREATE TABLE IF NOT EXISTS admin_notes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
 title VARCHAR(190) NOT NULL, body TEXT,
 priority VARCHAR(15) NOT NULL DEFAULT 'normal'
 CHECK(priority IN ('normal','important','urgent')),
 status VARCHAR(10) NOT NULL DEFAULT 'new'
 CHECK(status IN ('new','doing','done')),
 visibility VARCHAR(12) NOT NULL DEFAULT 'admin'
 CHECK(visibility IN ('admin','management')),
 due_at TIMESTAMP, pinned BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_admin_notes_status ON admin_notes(status,priority,due_at);
CREATE TABLE IF NOT EXISTS admin_v2_preferences (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 theme VARCHAR(10) NOT NULL DEFAULT 'dark',
 updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS admin_v2_restriction_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 admin_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 action VARCHAR(60) NOT NULL, reason VARCHAR(500),
 starts_at TIMESTAMP NOT NULL, ends_at TIMESTAMP,
 previous_state TEXT, new_state TEXT,
 created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_admin_restriction_user ON admin_v2_restriction_history(user_id,created_at);
CREATE INDEX IF NOT EXISTS idx_admin_restriction_action ON admin_v2_restriction_history(action,created_at);
CREATE TABLE IF NOT EXISTS site_notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(190) NOT NULL, message TEXT NOT NULL,
 locale VARCHAR(20) NOT NULL DEFAULT '*',
 button_label VARCHAR(100), button_url VARCHAR(500),
 starts_at TIMESTAMP, ends_at TIMESTAMP,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_site_notifications_active ON site_notifications(active,locale,starts_at,ends_at);
CREATE TABLE IF NOT EXISTS community_category_translations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id BIGINT NOT NULL REFERENCES community_categories(id) ON DELETE CASCADE,
 locale VARCHAR(20) NOT NULL, name VARCHAR(160) NOT NULL,
 slug VARCHAR(190) NOT NULL, description TEXT,
 UNIQUE(category_id,locale), UNIQUE(locale,slug)
);
CREATE INDEX IF NOT EXISTS idx_community_category_translations_locale ON community_category_translations(locale);
