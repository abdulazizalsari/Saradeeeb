-- Additive PHP schema port: throttling, 404 logs, media metadata and community controls.
CREATE TABLE IF NOT EXISTS auth_throttles (
 throttle_key CHAR(64) PRIMARY KEY, attempts INTEGER NOT NULL DEFAULT 0 CHECK(attempts>=0),
 last_attempt_at TIMESTAMP NOT NULL, locked_until TIMESTAMP
);
CREATE TABLE IF NOT EXISTS not_found_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 path VARCHAR(700) NOT NULL, locale VARCHAR(20), referrer VARCHAR(700),
 hits BIGINT NOT NULL DEFAULT 1 CHECK(hits>=0),
 last_seen_at TIMESTAMPTZ DEFAULT now(), created_at TIMESTAMPTZ DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_404_path_prefix ON not_found_logs(left(path,255));
CREATE INDEX IF NOT EXISTS idx_not_found_last_seen ON not_found_logs(last_seen_at);
CREATE TABLE IF NOT EXISTS media_folders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 parent_id BIGINT REFERENCES media_folders(id) ON DELETE CASCADE,
 name VARCHAR(160) NOT NULL,
 created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(parent_id,name)
);
CREATE INDEX IF NOT EXISTS idx_media_folders_parent ON media_folders(parent_id);
CREATE INDEX IF NOT EXISTS idx_media_folders_created_by ON media_folders(created_by);
CREATE TABLE IF NOT EXISTS media_tags (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, slug VARCHAR(120) NOT NULL UNIQUE,
 created_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS media_tag_map (
 media_id BIGINT NOT NULL REFERENCES media(id) ON DELETE CASCADE,
 tag_id BIGINT NOT NULL REFERENCES media_tags(id) ON DELETE CASCADE,
 PRIMARY KEY(media_id,tag_id)
);
CREATE TABLE IF NOT EXISTS media_usages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 media_id BIGINT NOT NULL REFERENCES media(id) ON DELETE CASCADE,
 entity_type VARCHAR(60) NOT NULL, entity_id BIGINT NOT NULL,
 field_name VARCHAR(80), created_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(media_id,entity_type,entity_id,field_name)
);
CREATE INDEX IF NOT EXISTS idx_media_usage_entity ON media_usages(entity_type,entity_id);
CREATE TABLE IF NOT EXISTS tag_translations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tag_id BIGINT NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
 locale VARCHAR(20) NOT NULL, name VARCHAR(160) NOT NULL,
 slug VARCHAR(190) NOT NULL, description TEXT,
 seo_title VARCHAR(255), seo_description VARCHAR(320),
 status VARCHAR(20) NOT NULL DEFAULT 'published'
 CHECK(status IN ('draft','review','published')),
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(tag_id,locale), UNIQUE(locale,slug)
);
CREATE INDEX IF NOT EXISTS idx_tag_translation_locale ON tag_translations(locale,status);
CREATE TABLE IF NOT EXISTS writer_card_preferences (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 template VARCHAR(30) NOT NULL DEFAULT 'classic',
 card_size VARCHAR(30) NOT NULL DEFAULT 'post',
 show_qr BOOLEAN NOT NULL DEFAULT TRUE,
 show_stats BOOLEAN NOT NULL DEFAULT TRUE,
 show_socials BOOLEAN NOT NULL DEFAULT TRUE,
 quote_text VARCHAR(180), style_json TEXT,
 updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS community_bans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
 reason VARCHAR(500), expires_at TIMESTAMP,
 created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_community_bans_expiry ON community_bans(expires_at);
CREATE TABLE IF NOT EXISTS community_topic_activity (
 topic_id BIGINT NOT NULL REFERENCES community_topics(id) ON DELETE CASCADE,
 activity_date DATE NOT NULL,
 views INTEGER NOT NULL DEFAULT 0 CHECK(views>=0),
 replies INTEGER NOT NULL DEFAULT 0 CHECK(replies>=0),
 likes INTEGER NOT NULL DEFAULT 0 CHECK(likes>=0),
 PRIMARY KEY(topic_id,activity_date)
);
CREATE INDEX IF NOT EXISTS idx_community_topic_activity_date ON community_topic_activity(activity_date);
