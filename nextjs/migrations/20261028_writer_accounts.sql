-- New site: writer accounts are new accounts, not restored legacy identities.
-- Apply through the controlled migration process before enabling the writer area.
-- Existing articles and their author associations are deliberately untouched.
ALTER TABLE web_accounts DROP CONSTRAINT IF EXISTS web_accounts_role_check;
ALTER TABLE web_accounts ADD CONSTRAINT web_accounts_role_check
  CHECK (role IN ('member','writer','trusted_writer','editor','admin'));
CREATE TABLE IF NOT EXISTS writer_drafts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 writer_account_id BIGINT NOT NULL REFERENCES web_accounts(id) ON DELETE CASCADE,
 title VARCHAR(240) NOT NULL,
 body TEXT NOT NULL DEFAULT '',
 status VARCHAR(24) NOT NULL DEFAULT 'draft'
   CHECK (status IN ('draft','submitted','changes_requested','approved','published')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS writer_drafts_owner_status
 ON writer_drafts(writer_account_id,status,updated_at DESC);
