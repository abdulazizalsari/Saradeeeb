-- Original PHP settings, translation_strings and newsletter_subscribers.
-- Idempotent additive migration. No source data imported yet.
CREATE TABLE IF NOT EXISTS settings (
 key VARCHAR(120) PRIMARY KEY,
 value TEXT NULL
);
CREATE TABLE IF NOT EXISTS translation_strings (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 namespace VARCHAR(80) NOT NULL,
 text_key VARCHAR(120) NOT NULL,
 locale VARCHAR(20) NOT NULL,
 value TEXT NULL,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_translation_string UNIQUE(namespace,text_key,locale)
);
CREATE INDEX IF NOT EXISTS idx_translation_strings_locale_namespace ON translation_strings(locale,namespace);
CREATE TABLE IF NOT EXISTS newsletter_subscribers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email VARCHAR(190) NOT NULL UNIQUE,
 locale VARCHAR(20) NOT NULL DEFAULT 'ar',
 status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK(status IN ('active','unsubscribed')),
 source VARCHAR(80) NOT NULL DEFAULT 'footer',
 consented_at TIMESTAMP NULL,
 created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_newsletter_status_created ON newsletter_subscribers(status,created_at);
CREATE INDEX IF NOT EXISTS idx_newsletter_locale ON newsletter_subscribers(locale);
