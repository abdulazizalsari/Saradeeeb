-- Additive original PHP contact, story and writer workflows.
CREATE TABLE IF NOT EXISTS story_submissions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL, email VARCHAR(190) NOT NULL,
 phone VARCHAR(60), title VARCHAR(220) NOT NULL, story TEXT NOT NULL,
 image VARCHAR(500), locale VARCHAR(20) NOT NULL DEFAULT 'ar',
 status VARCHAR(20) NOT NULL DEFAULT 'new'
 CHECK(status IN ('new','reviewed','accepted','rejected')),
 admin_note TEXT, created_at TIMESTAMPTZ DEFAULT now(),
 updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_story_status ON story_submissions(status,created_at);
CREATE INDEX IF NOT EXISTS idx_story_email ON story_submissions(email);
CREATE INDEX IF NOT EXISTS idx_story_locale ON story_submissions(locale);
CREATE TABLE IF NOT EXISTS contact_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL, email VARCHAR(190) NOT NULL,
 subject VARCHAR(220), message TEXT NOT NULL,
 locale VARCHAR(20) NOT NULL DEFAULT 'ar',
 status VARCHAR(20) NOT NULL DEFAULT 'new'
 CHECK(status IN ('new','read','replied','archived')),
 admin_note TEXT, created_at TIMESTAMPTZ DEFAULT now(),
 updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_contact_status ON contact_messages(status,created_at);
CREATE INDEX IF NOT EXISTS idx_contact_email ON contact_messages(email);
CREATE TABLE IF NOT EXISTS writer_thanks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 title VARCHAR(190), message TEXT,
 locale VARCHAR(20) NOT NULL DEFAULT 'ar',
 award_type VARCHAR(40) NOT NULL DEFAULT 'featured',
 announce_on_site BOOLEAN NOT NULL DEFAULT FALSE,
 starts_at TIMESTAMP, ends_at TIMESTAMP, notification_id BIGINT,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_writer_thanks_user ON writer_thanks(user_id,active);
CREATE TABLE IF NOT EXISTS writer_application_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 application_id BIGINT NOT NULL REFERENCES writer_applications(id) ON DELETE CASCADE,
 from_status VARCHAR(40), to_status VARCHAR(40) NOT NULL,
 admin_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
 note TEXT, created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_writer_app_history_application ON writer_application_history(application_id,created_at);
CREATE INDEX IF NOT EXISTS idx_writer_app_history_admin ON writer_application_history(admin_id);
CREATE TABLE IF NOT EXISTS writer_username_redirects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 old_username VARCHAR(120) NOT NULL UNIQUE,
 created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_writer_username_redirects_user ON writer_username_redirects(user_id);
CREATE TABLE IF NOT EXISTS community_user_preferences (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 email_replies BOOLEAN NOT NULL DEFAULT FALSE,
 email_mentions BOOLEAN NOT NULL DEFAULT FALSE,
 email_follows BOOLEAN NOT NULL DEFAULT FALSE,
 email_admin BOOLEAN NOT NULL DEFAULT TRUE,
 updated_at TIMESTAMPTZ DEFAULT now()
);
