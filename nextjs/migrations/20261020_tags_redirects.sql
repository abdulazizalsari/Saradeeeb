-- Safe, idempotent PostgreSQL migration of original PHP tables.
-- Source: database/schema.sql (tags, article_tags, redirects).
-- Existing rows are never deleted or rewritten.
CREATE TABLE IF NOT EXISTS tags (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  slug VARCHAR(140) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS article_tags (
  article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
  tag_id BIGINT NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
  PRIMARY KEY(article_id,tag_id)
);
CREATE TABLE IF NOT EXISTS redirects (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_path VARCHAR(500) NOT NULL UNIQUE,
  target_url VARCHAR(500) NOT NULL,
  http_code SMALLINT NOT NULL DEFAULT 301 CHECK (http_code IN (301,302,307,308))
);
