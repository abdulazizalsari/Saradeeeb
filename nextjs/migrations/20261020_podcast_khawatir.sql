-- Original PHP podcast, khawatir and writer profile translations.
-- Schema-only. Audio assets and content must be imported separately.
CREATE TABLE IF NOT EXISTS podcast_episodes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 article_id BIGINT REFERENCES articles(id) ON DELETE SET NULL,
 category_id BIGINT REFERENCES categories(id) ON DELETE SET NULL,
 created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 title VARCHAR(220) NOT NULL, slug VARCHAR(220) NOT NULL UNIQUE,
 excerpt TEXT, content TEXT, cover_image VARCHAR(500), og_image VARCHAR(500),
 episode_number INTEGER CHECK(episode_number>=0), duration VARCHAR(40),
 audio_source VARCHAR(10) NOT NULL DEFAULT 'external' CHECK(audio_source IN ('external','upload')),
 audio_url VARCHAR(1000) NOT NULL,
 status VARCHAR(15) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','published')),
 published_at TIMESTAMP, seo_title VARCHAR(255), seo_description VARCHAR(320),
 views BIGINT NOT NULL DEFAULT 0 CHECK(views>=0),
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_podcast_status ON podcast_episodes(status,published_at);
CREATE INDEX IF NOT EXISTS idx_podcast_category ON podcast_episodes(category_id,status);
CREATE INDEX IF NOT EXISTS idx_podcast_article ON podcast_episodes(article_id);
CREATE TABLE IF NOT EXISTS khawatir_categories (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, slug VARCHAR(120) NOT NULL UNIQUE,
 sort_order INTEGER NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS khawatir (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 category_id BIGINT REFERENCES khawatir_categories(id) ON DELETE SET NULL,
 reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 body VARCHAR(1200) NOT NULL, slug VARCHAR(220) NOT NULL UNIQUE,
 ownership VARCHAR(12) NOT NULL DEFAULT 'original' CHECK(ownership IN ('original','quoted')),
 original_author VARCHAR(190), source_name VARCHAR(255),
 source_url VARCHAR(700), image_path VARCHAR(500),
 status VARCHAR(12) NOT NULL DEFAULT 'draft'
 CHECK(status IN ('draft','review','changes','rejected','published')),
 review_note TEXT, published_at TIMESTAMP,
 views BIGINT NOT NULL DEFAULT 0 CHECK(views>=0),
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_khawatir_author ON khawatir(author_id,status,updated_at);
CREATE INDEX IF NOT EXISTS idx_khawatir_category ON khawatir(category_id,status,published_at);
CREATE TABLE IF NOT EXISTS podcast_episode_translations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 episode_id BIGINT NOT NULL REFERENCES podcast_episodes(id) ON DELETE CASCADE,
 locale VARCHAR(20) NOT NULL, title VARCHAR(220) NOT NULL,
 slug VARCHAR(220) NOT NULL, excerpt TEXT, content TEXT,
 seo_title VARCHAR(255), seo_description VARCHAR(320),
 og_title VARCHAR(255), og_description VARCHAR(320),
 status VARCHAR(15) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','review','published')),
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(episode_id,locale), UNIQUE(locale,slug)
);
CREATE INDEX IF NOT EXISTS idx_podcast_trans_locale ON podcast_episode_translations(locale,status);
CREATE TABLE IF NOT EXISTS khawatir_category_translations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category_id BIGINT NOT NULL REFERENCES khawatir_categories(id) ON DELETE CASCADE,
 locale VARCHAR(20) NOT NULL, name VARCHAR(120) NOT NULL,
 slug VARCHAR(160) NOT NULL, description TEXT,
 status VARCHAR(15) NOT NULL DEFAULT 'published' CHECK(status IN ('draft','review','published')),
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(category_id,locale), UNIQUE(locale,slug)
);
CREATE INDEX IF NOT EXISTS idx_khawatir_category_locale ON khawatir_category_translations(locale,status);
CREATE TABLE IF NOT EXISTS khawatir_translations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 khawatir_id BIGINT NOT NULL REFERENCES khawatir(id) ON DELETE CASCADE,
 locale VARCHAR(20) NOT NULL, title VARCHAR(220),
 slug VARCHAR(220) NOT NULL, body VARCHAR(1600) NOT NULL,
 description TEXT, seo_title VARCHAR(255), seo_description VARCHAR(320),
 status VARCHAR(15) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','review','published')),
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(khawatir_id,locale), UNIQUE(locale,slug)
);
CREATE INDEX IF NOT EXISTS idx_khawatir_trans_locale ON khawatir_translations(locale,status);
CREATE TABLE IF NOT EXISTS writer_profile_translations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 locale VARCHAR(20) NOT NULL, display_name VARCHAR(190),
 bio TEXT, professional_title VARCHAR(190), cv_summary TEXT,
 status VARCHAR(15) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','review','published')),
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(user_id,locale)
);
CREATE INDEX IF NOT EXISTS idx_writer_profile_trans_locale ON writer_profile_translations(locale,status);
