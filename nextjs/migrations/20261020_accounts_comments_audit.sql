-- Port of original PHP account, writer, comment, notification and audit tables.
-- Additive schema only. Does not synthesize personal information.
CREATE TABLE IF NOT EXISTS oauth_identities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 provider VARCHAR(40) NOT NULL, subject VARCHAR(255) NOT NULL,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 email VARCHAR(190), created_at TIMESTAMPTZ DEFAULT now(),
 updated_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(provider,subject), UNIQUE(provider,user_id)
);
CREATE INDEX IF NOT EXISTS idx_oauth_user ON oauth_identities(user_id);
CREATE TABLE IF NOT EXISTS writer_profiles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 professional_title VARCHAR(190), cv_summary TEXT, location VARCHAR(190),
 website VARCHAR(500), linkedin VARCHAR(500), portfolio_url VARCHAR(500),
 contact_email VARCHAR(190), experience_json TEXT, education_json TEXT,
 skills_json TEXT, certificates_json TEXT, languages_json TEXT,
 achievements_json TEXT, portfolio_json TEXT,
 is_public BOOLEAN NOT NULL DEFAULT FALSE,
 show_contact BOOLEAN NOT NULL DEFAULT FALSE,
 updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS article_comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
 parent_id BIGINT REFERENCES article_comments(id) ON DELETE CASCADE,
 user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
 guest_name VARCHAR(120), guest_email VARCHAR(190),
 content TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending'
 CHECK(status IN ('pending','approved','spam','trash')),
 ip_hash CHAR(64), user_agent VARCHAR(255),
 created_at TIMESTAMPTZ DEFAULT now(),
 updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_article_comments_article ON article_comments(article_id,status,created_at);
CREATE INDEX IF NOT EXISTS idx_article_comments_parent ON article_comments(parent_id);
CREATE INDEX IF NOT EXISTS idx_article_comments_user ON article_comments(user_id);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 type VARCHAR(80) NOT NULL DEFAULT 'info',
 title VARCHAR(190) NOT NULL, message TEXT, link VARCHAR(500),
 is_read BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id,is_read,created_at);
CREATE TABLE IF NOT EXISTS writer_applications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL, email VARCHAR(190) NOT NULL,
 phone VARCHAR(60) NOT NULL, country VARCHAR(120), city VARCHAR(120),
 topics VARCHAR(500), experience TEXT, sample_url VARCHAR(500),
 bio TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'new'
 CHECK(status IN ('new','reviewed','approved','rejected')),
 admin_note TEXT, verification_token_hash CHAR(64),
 verification_expires_at TIMESTAMP, email_verified_at TIMESTAMP,
 created_at TIMESTAMPTZ DEFAULT now(),
 updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_writer_applications_status ON writer_applications(status);
CREATE INDEX IF NOT EXISTS idx_writer_applications_email ON writer_applications(email);
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
 action VARCHAR(120) NOT NULL, target_type VARCHAR(80),
 target_id BIGINT, details TEXT, ip_address VARCHAR(64),
 user_agent VARCHAR(255), created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_audit_user ON audit_logs(user_id,created_at);
CREATE INDEX IF NOT EXISTS idx_audit_action ON audit_logs(action,created_at);
