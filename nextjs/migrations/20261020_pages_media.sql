-- Original PHP pages, page_translations and media schema.
-- Additive, idempotent. Does not import unavailable source rows.
CREATE TABLE IF NOT EXISTS pages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 status VARCHAR(20) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','published')),
 sort_order INTEGER NOT NULL DEFAULT 0,
 template VARCHAR(20) NOT NULL DEFAULT 'standard' CHECK(template IN ('standard','wide','landing')),
 deleted_at TIMESTAMP NULL,
 created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS page_translations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 page_id BIGINT NOT NULL REFERENCES pages(id) ON DELETE CASCADE,
 locale VARCHAR(20) NOT NULL,
 title VARCHAR(255) NOT NULL,
 slug VARCHAR(220) NOT NULL,
 content TEXT NOT NULL,
 content_mode VARCHAR(20) NOT NULL DEFAULT 'visual' CHECK(content_mode IN ('visual','html')),
 custom_css TEXT NULL, custom_js TEXT NULL,
 featured_image VARCHAR(500) NULL,
 seo_title VARCHAR(255) NULL,
 seo_description VARCHAR(320) NULL,
 canonical_url VARCHAR(700) NULL,
 show_title BOOLEAN NOT NULL DEFAULT TRUE,
 page_bg_color VARCHAR(20) NOT NULL DEFAULT '#ffffff',
 page_text_color VARCHAR(20) NOT NULL DEFAULT '#202522',
 content_width VARCHAR(20) NOT NULL DEFAULT 'standard',
 UNIQUE(locale,slug), UNIQUE(page_id,locale)
);
CREATE TABLE IF NOT EXISTS media (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
 path VARCHAR(500) NOT NULL, mime VARCHAR(120) NOT NULL,
 alt_text VARCHAR(255) NULL, title VARCHAR(190) NULL,
 caption VARCHAR(500) NULL, description TEXT NULL,
 original_name VARCHAR(255) NULL,
 width INTEGER NULL CHECK(width>=0),
 height INTEGER NULL CHECK(height>=0),
 size_bytes BIGINT NULL CHECK(size_bytes>=0),
 created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
