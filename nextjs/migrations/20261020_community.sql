-- Original PHP community topic, reply, like, follow, save and report tables.
-- Schema-only additive migration; preserves existing content.
CREATE TABLE IF NOT EXISTS community_topics (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 category_id BIGINT REFERENCES community_categories(id) ON DELETE SET NULL,
 locale VARCHAR(20) NOT NULL,
 article_id BIGINT REFERENCES articles(id) ON DELETE CASCADE,
 title VARCHAR(190) NOT NULL, slug VARCHAR(220) NOT NULL,
 excerpt VARCHAR(500), content TEXT NOT NULL,
 image VARCHAR(500), tags VARCHAR(500),
 status VARCHAR(20) NOT NULL DEFAULT 'open' CHECK(status IN ('open','closed','hidden')),
 pinned BOOLEAN NOT NULL DEFAULT FALSE, featured_week BOOLEAN NOT NULL DEFAULT FALSE,
 views BIGINT NOT NULL DEFAULT 0 CHECK(views>=0),
 replies_count INTEGER NOT NULL DEFAULT 0 CHECK(replies_count>=0),
 likes_count INTEGER NOT NULL DEFAULT 0 CHECK(likes_count>=0),
 last_activity_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(locale,slug), UNIQUE(article_id,locale)
);
CREATE INDEX IF NOT EXISTS idx_ctopic_locale ON community_topics(locale,status,last_activity_at);
CREATE INDEX IF NOT EXISTS idx_ctopic_category ON community_topics(category_id,locale);
CREATE INDEX IF NOT EXISTS idx_ctopic_author ON community_topics(author_id,created_at);
CREATE INDEX IF NOT EXISTS idx_ctopic_featured ON community_topics(featured_week,locale);
CREATE TABLE IF NOT EXISTS community_replies (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 topic_id BIGINT NOT NULL REFERENCES community_topics(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 reply_to_reply_id BIGINT REFERENCES community_replies(id) ON DELETE SET NULL,
 content TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'visible' CHECK(status IN ('visible','hidden','deleted')),
 likes_count INTEGER NOT NULL DEFAULT 0 CHECK(likes_count>=0),
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_creply_topic ON community_replies(topic_id,status,id);
CREATE INDEX IF NOT EXISTS idx_creply_user ON community_replies(user_id,created_at);
CREATE INDEX IF NOT EXISTS idx_creply_parent ON community_replies(reply_to_reply_id);
CREATE TABLE IF NOT EXISTS community_likes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 target_type VARCHAR(10) NOT NULL CHECK(target_type IN ('topic','reply')),
 target_id BIGINT NOT NULL, created_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(user_id,target_type,target_id)
);
CREATE INDEX IF NOT EXISTS idx_clike_target ON community_likes(target_type,target_id);
CREATE TABLE IF NOT EXISTS community_follows (
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 topic_id BIGINT NOT NULL REFERENCES community_topics(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ DEFAULT now(), PRIMARY KEY(user_id,topic_id)
);
CREATE INDEX IF NOT EXISTS idx_cfollow_topic ON community_follows(topic_id);
CREATE TABLE IF NOT EXISTS community_saves (
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 topic_id BIGINT NOT NULL REFERENCES community_topics(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ DEFAULT now(), PRIMARY KEY(user_id,topic_id)
);
CREATE INDEX IF NOT EXISTS idx_csave_topic ON community_saves(topic_id);
CREATE TABLE IF NOT EXISTS community_reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 target_type VARCHAR(10) NOT NULL CHECK(target_type IN ('topic','reply')),
 target_id BIGINT NOT NULL,
 reason VARCHAR(20) NOT NULL DEFAULT 'other'
 CHECK(reason IN ('abuse','spam','offtopic','copyright','other')),
 details VARCHAR(1000),
 status VARCHAR(20) NOT NULL DEFAULT 'open' CHECK(status IN ('open','resolved','dismissed')),
 reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 reviewed_at TIMESTAMP, created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_creport_status ON community_reports(status,created_at);
CREATE INDEX IF NOT EXISTS idx_creport_target ON community_reports(target_type,target_id);
CREATE INDEX IF NOT EXISTS idx_creport_user ON community_reports(user_id,target_type,target_id,status);
