-- PHP ads, homepage blocks, integrations, tracking, story of night.
-- WARNING: imported custom code must be reviewed before rendering on pages.
CREATE TABLE IF NOT EXISTS ads (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slot VARCHAR(80) NOT NULL, locale VARCHAR(20) NOT NULL DEFAULT '*',
 type VARCHAR(10) NOT NULL DEFAULT 'image' CHECK(type IN ('image','code')),
 label VARCHAR(120), advertiser_name VARCHAR(190), price_note VARCHAR(190),
 admin_note TEXT, image_url VARCHAR(500), target_url VARCHAR(500),
 code TEXT, active BOOLEAN NOT NULL DEFAULT TRUE,
 starts_at TIMESTAMP, ends_at TIMESTAMP, device VARCHAR(20) NOT NULL DEFAULT 'all',
 views BIGINT NOT NULL DEFAULT 0 CHECK(views>=0),
 clicks BIGINT NOT NULL DEFAULT 0 CHECK(clicks>=0),
 created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_ads_slot ON ads(slot,locale,active);
CREATE TABLE IF NOT EXISTS site_blocks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 type VARCHAR(10) NOT NULL DEFAULT 'image' CHECK(type IN ('image','ad')),
 slot VARCHAR(80) NOT NULL, locale VARCHAR(20) NOT NULL DEFAULT '*',
 title VARCHAR(190), image_url VARCHAR(500), target_url VARCHAR(500),
 ad_id BIGINT REFERENCES ads(id) ON DELETE SET NULL,
 sort_order INTEGER NOT NULL DEFAULT 0, active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_site_blocks_slot ON site_blocks(slot,locale,active,sort_order);
CREATE TABLE IF NOT EXISTS integrations (
 service_key VARCHAR(80) PRIMARY KEY, enabled BOOLEAN NOT NULL DEFAULT FALSE,
 config_json TEXT, updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_integrations_enabled ON integrations(enabled);
CREATE TABLE IF NOT EXISTS custom_tracking_codes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(160) NOT NULL,
 location VARCHAR(20) NOT NULL DEFAULT 'body_end'
 CHECK(location IN ('head','body_start','body_end')),
 consent_category VARCHAR(20) NOT NULL DEFAULT 'marketing'
 CHECK(consent_category IN ('essential','analytics','marketing','ads')),
 code TEXT NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
 updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ DEFAULT now(), updated_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_custom_tracking_active ON custom_tracking_codes(active,location);
CREATE INDEX IF NOT EXISTS idx_custom_tracking_consent ON custom_tracking_codes(consent_category);
CREATE TABLE IF NOT EXISTS story_of_night_selections (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 feature_date DATE NOT NULL, locale VARCHAR(20) NOT NULL DEFAULT 'ar',
 article_id BIGINT REFERENCES articles(id) ON DELETE SET NULL,
 selection_mode VARCHAR(12) NOT NULL DEFAULT 'automatic'
 CHECK(selection_mode IN ('automatic','manual')),
 selected_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 selected_at TIMESTAMPTZ DEFAULT now(), UNIQUE(feature_date,locale)
);
CREATE INDEX IF NOT EXISTS idx_story_night_article ON story_of_night_selections(article_id,feature_date);
CREATE TABLE IF NOT EXISTS story_of_night_exclusions (
 article_id BIGINT PRIMARY KEY REFERENCES articles(id) ON DELETE CASCADE,
 excluded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 reason VARCHAR(255), created_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS story_of_night_overrides (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 article_id BIGINT NOT NULL REFERENCES articles(id) ON DELETE CASCADE,
 starts_at TIMESTAMP NOT NULL, ends_at TIMESTAMP NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
 created_at TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_story_night_override_active ON story_of_night_overrides(active,starts_at,ends_at);
